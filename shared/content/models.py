# shared/content/models.py
"""
Data models for content asset bundles.

AssetFile     — a single generated file (image, markdown, json)
AssetBundle   — complete content package for one article
AssetStorageResult — outcome of persisting a bundle to disk

Immutable after construction. Phase 11B consumes AssetBundle
to drive WordPress media uploads and featured image attachment.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


@dataclass(frozen=True)
class AssetFile:
    """A single generated asset file."""
    key: str           # logical name: "featured", "facebook_landscape", etc.
    path: Path         # absolute path on disk
    mime_type: str     # "image/jpeg", "text/markdown", "application/json"
    size_bytes: int = 0

    def exists(self) -> bool:
        return self.path.exists()


@dataclass
class AssetBundle:
    """
    Complete content asset package for one article.

    Generated by AssetBuilder. Consumed by Phase 11B WordPress integration.
    All paths are absolute and guaranteed to exist after successful storage.
    """
    article_slug: str
    title: str
    summary: str
    keywords: list[str]
    storage_dir: Path
    assets: dict[str, AssetFile] = field(default_factory=dict)
    generated_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    branding_enabled: bool = True
    ads_enabled: bool = False
    metadata: dict[str, Any] = field(default_factory=dict)

    # Convenience accessors for Phase 11B
    @property
    def featured_image(self) -> AssetFile | None:
        return self.assets.get("featured")

    @property
    def facebook_landscape(self) -> AssetFile | None:
        return self.assets.get("facebook_landscape")

    @property
    def facebook_square(self) -> AssetFile | None:
        return self.assets.get("facebook_square")

    @property
    def instagram_square(self) -> AssetFile | None:
        return self.assets.get("instagram_square")

    @property
    def instagram_portrait(self) -> AssetFile | None:
        return self.assets.get("instagram_portrait")

    @property
    def story(self) -> AssetFile | None:
        return self.assets.get("story")

    @property
    def metadata_file(self) -> AssetFile | None:
        return self.assets.get("metadata")

    @property
    def article_file(self) -> AssetFile | None:
        return self.assets.get("article")

    def to_metadata_dict(self) -> dict[str, Any]:
        return {
            "article_slug": self.article_slug,
            "title": self.title,
            "summary": self.summary,
            "keywords": self.keywords,
            "generated_at": self.generated_at,
            "branding_enabled": self.branding_enabled,
            "ads_enabled": self.ads_enabled,
            "storage_dir": str(self.storage_dir),
            "assets": {
                key: {
                    "path": str(af.path),
                    "mime_type": af.mime_type,
                    "size_bytes": af.size_bytes,
                }
                for key, af in self.assets.items()
            },
            **self.metadata,
        }

    def __str__(self) -> str:
        return (
            f"AssetBundle(slug={self.article_slug!r}, "
            f"assets={list(self.assets.keys())}, "
            f"dir={self.storage_dir})"
        )


@dataclass
class AssetStorageResult:
    """Outcome of persisting an AssetBundle to disk."""
    success: bool
    bundle: AssetBundle | None = None
    error_message: str | None = None
    assets_written: int = 0
    storage_dir: Path | None = None

    def __str__(self) -> str:
        if self.success:
            return (
                f"AssetStorageResult(OK assets={self.assets_written} "
                f"dir={self.storage_dir})"
            )
        return f"AssetStorageResult(FAILED: {self.error_message})"
