# shared/wordpress/publisher.py
"""
WordPress publishing orchestration layer for ContentPilot.

Sits between modules and the WordPressClient.

Responsibilities:
- load WordPress config from environment
- build PostRequest from module content dict
- duplicate detection via shared/store
- call WordPressClient
- record publish outcome in SQLite
- return PostResponse — never raises

Environment variables (read via shared/config.py):
    WORDPRESS_URL           Full URL of the WordPress site (https://example.com)
    WORDPRESS_USERNAME      WordPress user with Editor role or higher
    WORDPRESS_APP_PASSWORD  Application Password from WP Admin → Users → Profile
    WORDPRESS_POST_STATUS   "draft" (default, safe) | "publish" (immediately live)
    WORDPRESS_TIMEOUT       HTTP timeout in seconds (default: 30)
    WORDPRESS_MAX_RETRIES   Retry attempts on transient failures (default: 3)

How to create an Application Password:
    1. WP Admin → Users → Your Profile
    2. Scroll to "Application Passwords"
    3. Enter name "ContentPilot" → click Add New
    4. Copy the generated password into .env as WORDPRESS_APP_PASSWORD
    ⚠️  Never use your main WP admin password here.

Post status safety:
    WORDPRESS_POST_STATUS=draft    → saved as draft, not visible to public (DEFAULT)
    WORDPRESS_POST_STATUS=publish  → immediately live on the site
    Always use "draft" until you have verified AI output quality in production.
"""

import logging
import os

from shared.store import already_published, compute_content_hash, record_publish

from .client import WordPressClient
from .models import PostRequest, PostResponse, WordPressConfig

logger = logging.getLogger(__name__)

_PLATFORM_KEY = "wordpress"
_VALID_STATUSES = {"draft", "publish", "pending", "private"}


# ---------------------------------------------------------------------------
# Config loader
# ---------------------------------------------------------------------------

def get_wordpress_config() -> WordPressConfig:
    """
    Build WordPressConfig from environment variables.

    Raises:
        ValueError: if WORDPRESS_URL, WORDPRESS_USERNAME, or
                    WORDPRESS_APP_PASSWORD are not set.
    """
    url = os.getenv("WORDPRESS_URL", "").strip()
    username = os.getenv("WORDPRESS_USERNAME", "").strip()
    app_password = os.getenv("WORDPRESS_APP_PASSWORD", "").strip()

    missing = [
        name for name, val in [
            ("WORDPRESS_URL", url),
            ("WORDPRESS_USERNAME", username),
            ("WORDPRESS_APP_PASSWORD", app_password),
        ]
        if not val
    ]
    if missing:
        raise ValueError(
            f"WordPress config incomplete — missing env vars: {', '.join(missing)}"
        )

    raw_status = os.getenv("WORDPRESS_POST_STATUS", "draft").strip().lower()
    if raw_status not in _VALID_STATUSES:
        logger.warning(
            "Invalid WORDPRESS_POST_STATUS=%r — falling back to 'draft'", raw_status
        )
        raw_status = "draft"

    timeout = int(os.getenv("WORDPRESS_TIMEOUT", "30"))
    max_retries = int(os.getenv("WORDPRESS_MAX_RETRIES", "3"))

    return WordPressConfig(
        base_url=url,
        username=username,
        app_password=app_password,
        default_status=raw_status,
        timeout_seconds=timeout,
        max_retries=max_retries,
    )


# ---------------------------------------------------------------------------
# Public interface
# ---------------------------------------------------------------------------

def publish_post(
    title: str,
    content: str,
    *,
    excerpt: str | None = None,
    categories: list[int] | None = None,
    tags: list[int] | None = None,
    slug: str | None = None,
    module_name: str = "unknown",
    target_key: str = "wordpress_main",
    mode: str | None = None,
    config: WordPressConfig | None = None,
    client: WordPressClient | None = None,
) -> PostResponse:
    """
    Publish (or draft) a post to WordPress.

    Args:
        title:       Post title. Required.
        content:     Post body HTML. Required.
        excerpt:     Optional excerpt / meta description.
        categories:  Optional list of WordPress category IDs.
        tags:        Optional list of WordPress tag IDs.
        slug:        Optional URL slug. Auto-generated by WP if None.
        module_name: Used for publish history tracking.
        target_key:  Logical target name for dedup (e.g. "wordpress_main").
                     Use different keys for different WP sites.
        mode:        "mock" | "real" | None.
                     If None, reads PUBLISH_MODE from environment.
        config:      Optional pre-built WordPressConfig (for testing).
        client:      Optional pre-built WordPressClient (for testing).

    Returns:
        PostResponse — never raises.
    """
    publish_mode = (mode or os.getenv("PUBLISH_MODE", "disabled")).strip().lower()

    if publish_mode == "disabled":
        logger.info(
            "wordpress_publish_skipped | reason=disabled | target=%s", target_key
        )
        return PostResponse(
            success=False,
            error_message="Publishing disabled (PUBLISH_MODE=disabled)",
            metadata={"mode": "disabled", "target": target_key},
        )

    if publish_mode == "mock":
        return _mock_publish(title, content, target_key)

    if publish_mode != "real":
        logger.warning(
            "Unknown PUBLISH_MODE=%r — treating as disabled", publish_mode
        )
        return PostResponse(
            success=False,
            error_message=f"Unknown publish mode: {publish_mode!r}",
            metadata={"target": target_key},
        )

    # --- Real publish from here ---

    content_hash = compute_content_hash(f"{title}::{content}")

    if already_published(content_hash, target_key):
        logger.info(
            "wordpress_duplicate_skipped | target=%s | hash=%s",
            target_key, content_hash[:12],
        )
        return PostResponse(
            success=True,
            metadata={"target": target_key, "duplicate": True},
        )

    try:
        cfg = config or get_wordpress_config()
    except ValueError as exc:
        logger.error(
            "wordpress_config_error | target=%s | error=%s", target_key, exc
        )
        return PostResponse(
            success=False,
            error_message=str(exc),
            retryable=False,
            metadata={"target": target_key},
        )

    post_request = PostRequest(
        title=title,
        content=content,
        status=cfg.default_status,
        excerpt=excerpt,
        categories=categories,
        tags=tags,
        slug=slug,
    )

    wp = client or WordPressClient(cfg)
    result = wp.create_post(post_request)

    _record_outcome(
        result=result,
        content_hash=content_hash,
        target_key=target_key,
        module_name=module_name,
    )

    return result


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _mock_publish(title: str, content: str, target_key: str) -> PostResponse:
    """Return a fake successful PostResponse without hitting the API."""
    import uuid

    # Still reads the configured status so mock behaviour matches real
    raw_status = os.getenv("WORDPRESS_POST_STATUS", "draft").strip().lower()
    post_status = raw_status if raw_status in _VALID_STATUSES else "draft"

    fake_id = uuid.uuid4().int % 100_000

    logger.debug(
        "wordpress_mock_publish | target=%s | status=%s | title=%r | fake_id=%d",
        target_key, post_status, title[:60], fake_id,
    )

    return PostResponse(
        success=True,
        wordpress_post_id=fake_id,
        url=f"https://example.com/?p={fake_id}",
        status=post_status,
        metadata={
            "mode": "mock",
            "target": target_key,
            "wp_status": post_status,
        },
    )


def _record_outcome(
    result: PostResponse,
    content_hash: str,
    target_key: str,
    module_name: str,
) -> None:
    """Persist publish outcome to SQLite history store."""
    try:
        record_publish(
            content_hash=content_hash,
            target_key=target_key,
            platform=_PLATFORM_KEY,
            module_name=module_name,
            status="success" if result.success else "failed",
            external_post_id=(
                str(result.wordpress_post_id) if result.wordpress_post_id else None
            ),
            error_message=result.error_message,
        )
    except Exception as exc:
        # Never let store failure crash the publish result
        logger.warning(
            "wordpress_store_record_failed | target=%s | error=%s",
            target_key, exc,
        )
